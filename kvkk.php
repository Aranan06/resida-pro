  <h2>1. İşlenen Veriler</h2>
  <ul>
    <li>Kimlik: Ad soyad</li>
    <li>İletişim: Telefon, e-posta, adres, daire/blok bilgisi</li>
    <li>İşlem: Aidat, ödeme dekontu, giriş kayıtları (IP, zaman)</li>
  </ul>

  <h2>2. İşleme Amaçları</h2>
  <ul>
    <li>Aidat takibi ve tahsilat süreçlerinin yürütülmesi</li>
    <li>Site yönetimi ile iletişim (duyuru, etkinlik, WhatsApp hatırlatma)</li>
    <li>Yasal yükümlülüklerin yerine getirilmesi ve uyuşmazlık çözümü</li>
  </ul>

  <h2>3. Hukuki Sebep</h2>
  <p>KVKK m.5/2-a (kanunlarda açıkça öngörülme), m.5/2-c (sözleşmenin ifası) ve m.5/2-f (meşru menfaat) ile açık rızanız.</p>

  <h2>4. Aktarım</h2>
  <p>Verileriniz yalnızca site yönetiminiz ve barındırma sağlayıcısı ile paylaşılır. Yurtdışına aktarım yapılmaz. Ödeme kuruluşuna (iyzico) yalnızca ödeme anında aktarım olur.</p>

  <h2>5. Saklama</h2>
  <p>Veriler abonelik süresince ve sonrasında yasal zamanaşımı (10 yıl) boyunca saklanır, sonra silinir/anonimleştirilir.</p>

  <h2>6. Haklarınız (KVKK m.11)</h2>
  <p>Verilerinize erişme, düzeltme, silme, işlenmeye itiraz ve zarar giderimi haklarınız vardır. Başvuru: <strong>kvkk@residapro.com</strong> (örnek). Talepleriniz 30 gün içinde yanıtlanır.</p>

  <h2>7. Açık Rıza</h2>
  <p>Sakin ekleme formundaki “KVKK Aydınlatma Metnini okudum, onaylıyorum” kutusunu işaretleyerek verilerinizin bu metin kapsamındaki işlenmesine açık rıza verirsiniz. Onay zamanı ve IP adresiniz kayıt altına alınır.</p>

